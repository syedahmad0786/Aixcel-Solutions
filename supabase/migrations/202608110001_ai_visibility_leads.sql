create function public.record_ai_visibility_booking(
  p_email_normalized text,
  p_event_type text,
  p_event_key text,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lead public.ai_visibility_leads%rowtype;
  v_event text := lower(btrim(coalesce(p_event_type, 'booking_event')));
begin
  select leads.*
  into v_lead
  from public.ai_visibility_leads as leads
  where leads.email_normalized = lower(btrim(p_email_normalized))
    and leads.last_submitted_at >= now() - interval '180 days'
  order by leads.last_submitted_at desc
  limit 1
  for update;

  if not found then
    insert into public.ai_visibility_booking_events (email_normalized, event_type, event_key, payload)
    values (lower(btrim(p_email_normalized)), left(v_event, 120), left(p_event_key, 300), coalesce(p_payload, '{}'::jsonb))
    on conflict (event_key) do nothing;
    return jsonb_build_object('matched', false);
  end if;

  insert into public.ai_visibility_booking_events (email_normalized, event_type, event_key, payload, matched_lead_id)
  values (lower(btrim(p_email_normalized)), left(v_event, 120), left(p_event_key, 300), coalesce(p_payload, '{}'::jsonb), v_lead.id)
  on conflict (event_key) do update set matched_lead_id = excluded.matched_lead_id;

  insert into public.ai_visibility_lead_events (lead_id, event_type, event_key, payload)
  values (v_lead.id, left(v_event, 80), left(p_event_key, 300), coalesce(p_payload, '{}'::jsonb))
  on conflict (event_key) do nothing;

  if v_event like '%cancel%' and v_lead.status = 'booked' then
    update public.ai_visibility_leads set status = 'qualified', next_action_at = now() where id = v_lead.id;
  elsif (v_event like '%created%' or v_event like '%rescheduled%' or v_event like '%booking%')
    and v_lead.status in ('new', 'contacted', 'qualified') then
    update public.ai_visibility_leads set status = 'booked', next_action_at = null where id = v_lead.id;
  end if;

  return jsonb_build_object('matched', true, 'lead_id', v_lead.id);
end;
$$;

revoke all on function public.record_ai_visibility_booking(text, text, text, jsonb)
from public, anon, authenticated;
grant execute on function public.record_ai_visibility_booking(text, text, text, jsonb)
to service_role;

create function public.log_ai_visibility_lead_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.status is distinct from new.status
    or old.owner_user_id is distinct from new.owner_user_id
    or old.next_action_at is distinct from new.next_action_at then
    insert into public.ai_visibility_lead_events (lead_id, event_type, payload, actor_user_id)
    values (
      new.id,
      'lead_updated',
      jsonb_build_object(
        'statusFrom', old.status,
        'statusTo', new.status,
        'ownerChanged', old.owner_user_id is distinct from new.owner_user_id,
        'nextActionAt', new.next_action_at
      ),
      auth.uid()
    );
  end if;
  return new;
end;
$$;

create trigger ai_visibility_lead_change_event
after update on public.ai_visibility_leads
for each row execute function public.log_ai_visibility_lead_change();

revoke all on function public.log_ai_visibility_lead_change()
from public, anon, authenticated;
