create table public.ai_visibility_leads (
  id uuid primary key default gen_random_uuid(),
  request_type text not null check (request_type in ('free_audit', 'guide_download', 'strategy_call')),
  full_name text not null check (char_length(btrim(full_name)) between 1 and 120),
  email_normalized text not null check (
    email_normalized = lower(btrim(email_normalized))
    and char_length(email_normalized) between 3 and 320
  ),
  company_name text not null check (char_length(btrim(company_name)) between 1 and 160),
  website_url text not null check (website_url ~ '^https?://[^[:space:]]+$' and char_length(website_url) <= 2048),
  annual_revenue_range text not null check (annual_revenue_range in ('pre_revenue', 'under_250k', '250k_1m', '1m_5m', '5m_20m', '20m_plus', 'prefer_not_to_say')),
  role_title text check (role_title is null or char_length(btrim(role_title)) between 1 and 120),
  ai_goal text check (ai_goal is null or char_length(btrim(ai_goal)) between 1 and 1500),
  timing text check (timing is null or timing in ('now', '30-60-days', 'later', 'exploring')),
  source_context jsonb not null default '{}'::jsonb check (jsonb_typeof(source_context) = 'object'),
  status text not null default 'new' check (status in ('new', 'contacted', 'qualified', 'booked', 'proposal', 'won', 'lost', 'spam')),
  owner_user_id uuid references auth.users (id) on delete set null,
  next_action_at timestamptz,
  consent_version text not null check (char_length(btrim(consent_version)) between 1 and 64),
  consented_at timestamptz not null default now(),
  first_submitted_at timestamptz not null default now(),
  last_submitted_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.ai_visibility_lead_events (
  id bigint generated by default as identity primary key,
  lead_id uuid not null references public.ai_visibility_leads (id) on delete cascade,
  event_type text not null check (char_length(btrim(event_type)) between 1 and 80),
  event_key text unique check (event_key is null or char_length(event_key) between 1 and 300),
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  actor_user_id uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.ai_visibility_booking_events (
  id bigint generated by default as identity primary key,
