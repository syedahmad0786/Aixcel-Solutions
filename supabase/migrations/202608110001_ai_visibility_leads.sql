create function public.capture_ai_visibility_lead(
  p_submission_id uuid,
  p_fingerprint text,
  p_request_type text,
  p_name text,
  p_email_normalized text,
  p_company_name text,
  p_website_url text,
  p_role_title text,
  p_ai_goal text,
  p_timing text,
  p_annual_revenue_range text,
  p_source_context jsonb,
  p_consent_version text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_limit public.lead_capture_rate_limits%rowtype;
  v_lead public.ai_visibility_leads%rowtype;
  v_created boolean := false;
begin
  if p_submission_id is null
    or p_fingerprint !~ '^[0-9a-f]{64}$'
    or p_request_type not in ('free_audit', 'guide_download', 'strategy_call')
    or char_length(btrim(coalesce(p_name, ''))) not between 1 and 120
    or char_length(lower(btrim(coalesce(p_email_normalized, '')))) not between 3 and 320
    or char_length(btrim(coalesce(p_company_name, ''))) not between 1 and 160
    or p_annual_revenue_range not in ('pre_revenue', 'under_250k', '250k_1m', '1m_5m', '5m_20m', '20m_plus', 'prefer_not_to_say')
    or (p_role_title is not null and char_length(btrim(p_role_title)) not between 1 and 120)
    or (p_ai_goal is not null and char_length(btrim(p_ai_goal)) not between 1 and 1500)
    or (p_timing is not null and p_timing not in ('now', '30-60-days', 'later', 'exploring'))
    or (p_request_type = 'free_audit' and (
      char_length(btrim(coalesce(p_role_title, ''))) not between 1 and 120
      or char_length(btrim(coalesce(p_ai_goal, ''))) not between 1 and 1500
      or p_timing not in ('now', '30-60-days', 'later', 'exploring')
    ))
    or jsonb_typeof(coalesce(p_source_context, '{}'::jsonb)) <> 'object' then
    return jsonb_build_object('reason', 'invalid_claim');
  end if;

  insert into public.lead_capture_rate_limits as limits (fingerprint, window_started_at, attempt_count)
  values (p_fingerprint, now(), 1)
  on conflict (fingerprint) do update
  set
    window_started_at = case when limits.window_started_at < now() - interval '1 hour' then now() else limits.window_started_at end,
    attempt_count = case when limits.window_started_at < now() - interval '1 hour' then 1 else limits.attempt_count + 1 end
  returning * into v_limit;

  if v_limit.attempt_count > 5 then
    return jsonb_build_object('reason', 'rate_limited');
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(lower(btrim(p_email_normalized)) || '|' || p_website_url, 0)
  );

  select leads.*
  into v_lead
  from public.ai_visibility_leads as leads
  where leads.email_normalized = lower(btrim(p_email_normalized))
    and leads.website_url = p_website_url
  order by leads.last_submitted_at desc
  limit 1
  for update;

  if found then
    update public.ai_visibility_leads
    set
      request_type = p_request_type,
      full_name = btrim(p_name),
      company_name = btrim(p_company_name),
      annual_revenue_range = p_annual_revenue_range,
      role_title = nullif(btrim(coalesce(p_role_title, '')), ''),
      ai_goal = nullif(btrim(coalesce(p_ai_goal, '')), ''),
      timing = p_timing,
      source_context = coalesce(p_source_context, '{}'::jsonb),
      consent_version = btrim(p_consent_version),
      consented_at = now(),
      last_submitted_at = now()
    where id = v_lead.id
    returning * into v_lead;
  else
    insert into public.ai_visibility_leads (
      request_type,
      full_name,
      email_normalized,
      company_name,
      website_url,
      annual_revenue_range,
      role_title,
      ai_goal,
      timing,
      source_context,
      consent_version
    ) values (
      p_request_type,
      btrim(p_name),
      lower(btrim(p_email_normalized)),
      btrim(p_company_name),
      p_website_url,
      p_annual_revenue_range,
      nullif(btrim(coalesce(p_role_title, '')), ''),
      nullif(btrim(coalesce(p_ai_goal, '')), ''),
      p_timing,
      coalesce(p_source_context, '{}'::jsonb),
      btrim(p_consent_version)
    )
    returning * into v_lead;
    v_created := true;
  end if;

  insert into public.ai_visibility_lead_events (lead_id, event_type, event_key, payload)
  values (
    v_lead.id,
    'submission',
    'submission:' || p_submission_id::text,
    jsonb_build_object('source', coalesce(p_source_context, '{}'::jsonb), 'requestType', p_request_type, 'annualRevenueRange', p_annual_revenue_range, 'deduplicated', not v_created)
  )
  on conflict (event_key) do nothing;

  return jsonb_build_object('reason', case when v_created then 'created' else 'deduplicated' end, 'lead_id', v_lead.id, 'created', v_created);
end;
$$;

revoke all on function public.capture_ai_visibility_lead(uuid, text, text, text, text, text, text, text, text, text, text, jsonb, text)
from public, anon, authenticated;
grant execute on function public.capture_ai_visibility_lead(uuid, text, text, text, text, text, text, text, text, text, text, jsonb, text)
